-- Courses: learning courses with lesson progress, their creators, and custom groups.
-- The schema isn't managed by the app (no ddl-auto, no migrations), so run this by hand,
-- once per database, BEFORE deploying the API that uses it:
--   psql -d <database> -f db/2026-11-25-courses.sql
-- Safe to re-run. It runs in one transaction: if anything fails, nothing changes.
--
-- A course belongs to at most one group. Deleting a group leaves its courses ungrouped.
-- Creators work like Library's authors: a reusable list, unique ignoring case and spaces.

BEGIN;

CREATE TABLE IF NOT EXISTS course_creators (
  id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(255) NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS course_creators_name_unique ON course_creators (lower(trim(name)));

CREATE TABLE IF NOT EXISTS course_groups (
  id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name     varchar(255) NOT NULL,
  -- Display order, chosen by the user (0 first).
  position integer NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS course_groups_name_unique ON course_groups (lower(trim(name)));

CREATE TABLE IF NOT EXISTS courses (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title             varchar(255)  NOT NULL,
  creator_id        integer       NOT NULL REFERENCES course_creators (id),
  group_id          integer       REFERENCES course_groups (id) ON DELETE SET NULL,
  total_lessons     integer       NOT NULL CHECK (total_lessons BETWEEN 1 AND 10000),
  completed_lessons integer       NOT NULL DEFAULT 0,
  url               varchar(2048),
  s3_url            varchar(2048),
  created_at        timestamptz   NOT NULL DEFAULT now(),
  CONSTRAINT courses_completed_within_total CHECK (completed_lessons BETWEEN 0 AND total_lessons)
);
CREATE INDEX IF NOT EXISTS courses_group_id ON courses (group_id);
CREATE INDEX IF NOT EXISTS courses_creator_id ON courses (creator_id);

COMMIT;
